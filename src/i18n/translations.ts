export function getTranslation(lang: Language) {
  return translations[lang];
}

export function getStatusLabel(status: RepairStatus, lang: Language): string {
  return translations[lang].status[status] || status;
}

export function getBusinessTypeLabel(
  type: BusinessType,
  lang: Language,
  customOptions?: BusinessTypeOption[]
): string {
  if (customOptions) {
    const found = customOptions.find((o) => o.id === type);
    if (found) return lang === 'gu' ? found.labelGu : found.labelEn;
  }
  const builtIn = translations[lang].businessTypes as Record<string, string>;
  return builtIn[type] || type;
}
